// GenerateDockerCompose produces a docker-compose.yaml with one service per agent,
// a shared context volume, and env var passthrough (no secret values).
func GenerateDockerCompose(cfg *config.Config) string {
	var b strings.Builder

	b.WriteString("# Generated by Rakitsu — do not edit manually\n")
	b.WriteString("# Local development setup for multi-agent export\n")
	b.WriteString(fmt.Sprintf("# Project: %s\n\n", shared.SanitizeComment(cfg.Name)))

	b.WriteString("services:\n")
	for _, agent := range cfg.Agents {
		agentID := shared.SanitizeID(agent.Name)
		b.WriteString(fmt.Sprintf("  agent-%s:\n", agentID))
		b.WriteString("    image: ghcr.io/openclaw/openclaw:latest\n")
		b.WriteString("    volumes:\n")
		b.WriteString(fmt.Sprintf("      - ./agent-%s/openclaw.json:/home/node/.openclaw/openclaw.json:ro\n", agentID))
		b.WriteString(fmt.Sprintf("      - ./agent-%s/sandbox-policy.yaml:/home/node/.openclaw/sandbox-policy.yaml:ro\n", agentID))
		b.WriteString("      - context-data:/workspace/context\n")

		// Environment variables: passthrough only (no values, no secret leakage)
		envVars := CollectEnvVarNames(cfg)
		if len(envVars) > 0 {
			b.WriteString("    environment:\n")
			for _, envVar := range envVars {
				b.WriteString(fmt.Sprintf("      - %s\n", envVar))
			}
		}

		b.WriteString("    networks:\n")
		b.WriteString("      - internal\n")
	}

	b.WriteString("\nnetworks:\n")
	b.WriteString("  internal:\n")
	b.WriteString("    internal: true\n")

	b.WriteString("\nvolumes:\n")
	b.WriteString("  context-data:\n")

	return b.String()
}

// CollectEnvVarNames extracts environment variable names from provider configs.
// Returns only the names (e.g., "OPENAI_API_KEY"), never resolved values.
func CollectEnvVarNames(cfg *config.Config) []string {
	seen := map[string]bool{}
	var names []string

	for _, pDef := range cfg.Settings.Providers {
		if shared.IsEnvRef(pDef.APIKey) {
			name := pDef.APIKey[2 : len(pDef.APIKey)-1] // extract from ${...}
			if !seen[name] {
				seen[name] = true
				names = append(names, name)
			}
		}
		if shared.IsEnvRef(pDef.BaseURL) {
			name := pDef.BaseURL[2 : len(pDef.BaseURL)-1]
			if !seen[name] {
				seen[name] = true
				names = append(names, name)
			}
		}
	}

	return names
}
