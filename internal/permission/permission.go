// Package permission is the permission broker core: it decides whether a
// tool action that falls outside the configured scope may run, asking the
// human through a Prompter when needed.
//
// Fail closed: only Allow or Deny ever leave this package. A missing Gate,
// missing Prompter, prompter error, timeout, cancellation, rate limit,
// unknown option or display failure all resolve to Deny.
package permission

import (
	"context"
	"errors"
	"fmt"
	"os"
)

// Kind is the category of action being authorized.
type Kind string

const (
	KindCLIExec Kind = "cli_exec"
	KindFSWrite Kind = "fs_write"
	KindFSRead  Kind = "fs_read"
)

func (k Kind) known() bool {
	switch k {
	case KindCLIExec, KindFSWrite, KindFSRead:
		return true
	}
	return false
}

// Reason says why an action needs approval.
type Reason string

const (
	ReasonNotAllowlisted   Reason = "not_allowlisted"
	ReasonPathOutside      Reason = "path_outside_allowed"
	ReasonRisky            Reason = "risky_class"
	ReasonPersistencePoint Reason = "persistence_point"
)

// Risk is the risky class of a command. Any value other than RiskNone
// (including values this package does not know) is treated as risky.
type Risk string

const (
	RiskNone         Risk = ""
	RiskShell        Risk = "shell"
	RiskInterpreter  Risk = "interpreter"
	RiskReExec       Risk = "reexec"
	RiskInstaller    Risk = "installer"
	RiskDownloadExec Risk = "download_exec"
	RiskCodeExecFlag Risk = "code_exec_flag"
	RiskDestructive  Risk = "destructive"
)

// FileID is a file identity captured at request time. Compare with SameFile.
type FileID struct{ info os.FileInfo }

// NewFileID captures the identity of an already-stat'ed file.
func NewFileID(fi os.FileInfo) FileID { return FileID{info: fi} }

// IsZero reports whether no identity was captured.
func (f FileID) IsZero() bool { return f.info == nil }

// SameFile reports whether both identities refer to the same file. A zero
// FileID never matches anything.
func (f FileID) SameFile(o FileID) bool {
	if f.info == nil || o.info == nil {
		return false
	}
	return os.SameFile(f.info, o.info)
}

// Boundary is the execution boundary of the action. Type is "host" in this
// slice; Label is the honest, broker-owned description.
type Boundary struct{ Type, Label string }

// Request describes one action that needs a decision. Adapters build it from
// the normalized operation; the model's text appears only in Rationale.
type Request struct {
	ID          string // broker-generated by the Gate; any caller value is replaced
	Kind        Kind
	Tool, Agent string
	ParentChain []string // root .. direct parent (display/audit)
	ToolCallID  string   // model-supplied; display/correlation only, never a key
	Argv        []string // final argv; Argv[0] == BinaryPath for cli
	BinaryPath  string
	Binary      FileID
	Subcommand  string // display only; KeyFor derives its own from Argv
	Cwd         string
	Paths       []string // all offending canonical paths
	EnvNames    []string // env names the child will receive
	Boundary    Boundary
	Reasons     []Reason
	Risk        Risk
	Rationale   string // model text; untrusted; display only, never in telemetry
}

func (r Request) has(reason Reason) bool {
	for _, x := range r.Reasons {
		if x == reason {
			return true
		}
	}
	return false
}

// Decision is the outcome of a check. Only Allow and Deny are exported;
// the zero value is Deny.
type Decision int

const (
	Deny Decision = iota
	Allow
	// decisionAsk is internal: it never leaves the package.
	decisionAsk
)

func (d Decision) String() string {
	if d == Allow {
		return "allow"
	}
	return "deny"
}

// Scope is how long an Allow lasts. The zero value is ScopeNone.
type Scope int

const (
	ScopeNone Scope = iota
	ScopeOnce
	ScopeSession
)

func (s Scope) String() string {
	switch s {
	case ScopeOnce:
		return "once"
	case ScopeSession:
		return "session"
	}
	return "none"
}

// Decision sources, matching telemetry.PermissionDecidedPayload.Source.
const (
	SourceClientSelected     = "client_selected"
	SourceSessionGrant       = "session_grant"
	SourcePolicy             = "policy"
	SourceTimeout            = "timeout"
	SourceCancelled          = "cancelled"
	SourceDisconnected       = "disconnected"
	SourceUnknownOption      = "unknown_option"
	SourceRateLimited        = "rate_limited"
	SourceNoChannel          = "no_channel"
	SourceDisplayRefused     = "display_refused"
	SourceRevalidationFailed = "revalidation_failed"
)

// Verdict is the result of Authorize. Its zero value is a Deny.
type Verdict struct {
	Decision Decision
	Scope    Scope
	Source   string
	Message  string // agent-facing, actionable
}

// Allowed reports whether the verdict is an Allow.
func (v Verdict) Allowed() bool { return v.Decision == Allow }

// Card is what the Prompter shows. It is built by the broker only.
type Card struct {
	Title            string
	Body             string
	PersistencePoint bool
	Risky            bool
}

// Option is one choice offered to the human. IDs are random per request.
// Allow options have ScopeOnce or ScopeSession; the deny option has ScopeNone.
type Option struct {
	ID, Name string
	Scope    Scope
}

// Answer is what the Prompter reports back.
type Answer struct {
	OptionID  string
	Cancelled bool
}

// Prompter delivers a card to the human and returns the selected option.
// Any error means Deny.
type Prompter interface {
	Prompt(ctx context.Context, card Card, options []Option) (Answer, error)
}

var (
	// ErrNoChannel means there is no way to reach a human.
	ErrNoChannel = errors.New("permission: no approval channel")
	// ErrDisconnected means the approval channel went away mid-request.
	ErrDisconnected = errors.New("permission: approval channel disconnected")
)

// DenyPrompter is the Prompter for entry points with no approval channel.
// It always fails, so every Ask becomes Deny with source "no_channel".
type DenyPrompter struct{ Reason string }

// Prompt always returns ErrNoChannel.
func (d DenyPrompter) Prompt(context.Context, Card, []Option) (Answer, error) {
	return Answer{}, fmt.Errorf("%w: %s", ErrNoChannel, d.Reason)
}
